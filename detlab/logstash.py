"""Write the Logstash pipeline and the Elasticsearch index template of the stack.

Both come from detlab/fields.py, the same mapping the rules are converted
with. Logstash therefore stores the simulator's and the log generator's events
under exactly the field names the converted rules query.
"""

import json

from detlab import authlog
from detlab.fields import AUTH_LOG_FIELDS, FIELD_MAP

LIVE_INDEX = "detlab-live-events"
# Fields Logstash keeps at the top level. Any other field of a Windows event moves under winlog.event_data.
ECS_ROOTS = ["@timestamp", "@version", "tags", "event", "host", "process", "user", "registry", "file",
             "destination", "source", "dns", "winlog", "labels", "log", "message", "network"]


def _bracket(dotted: str) -> str:
    """process.parent.executable -> [process][parent][executable]"""
    return "".join(f"[{part}]" for part in dotted.split("."))


def pipeline() -> str:
    renames = "\n".join(f'        "{sigma}" => "{_bracket(ecs)}"'
                        for sigma, ecs in FIELD_MAP.items() if sigma != "EventID" and sigma not in AUTH_LOG_FIELDS)
    keep = ", ".join(f'"{name}"' for name in ECS_ROOTS)
    return f'''# Generated by `python -m detlab build` from detlab/fields.py. Do not edit it by hand.
#
# Reads what attack-simulator and log-generator write under stack/logs and stores it in
# Elasticsearch as ECS documents, in the index {LIVE_INDEX}.

input {{
  file {{
    path => "/var/log/detection-lab/windows/*.json"
    codec => "json"
    start_position => "beginning"
    sincedb_path => "/usr/share/logstash/data/sincedb-windows"
    tags => ["windows"]
  }}
  file {{
    path => "/var/log/detection-lab/linux/auth.log"
    start_position => "beginning"
    sincedb_path => "/usr/share/logstash/data/sincedb-linux"
    tags => ["linux_auth"]
  }}
  file {{
    path => "/var/log/detection-lab/network/firewall.log"
    start_position => "beginning"
    sincedb_path => "/usr/share/logstash/data/sincedb-firewall"
    tags => ["firewall"]
  }}
}}

filter {{
  # The file input names the Logstash container as the host. The events name their own.
  mutate {{ remove_field => ["host", "log", "[event][original]"] }}

  if "windows" in [tags] {{
    # The simulator stamps "timestamp", the log generator "UtcTime" (Sysmon) or "TimeCreated".
    date {{ match => ["timestamp", "ISO8601"] remove_field => ["timestamp"] }}
    date {{ match => ["UtcTime", "ISO8601"] remove_field => ["UtcTime"] }}
    date {{ match => ["TimeCreated", "ISO8601"] remove_field => ["TimeCreated"] }}

    # Which log the event belongs to. The log generator says so itself, the simulator only by event type.
    if [Channel] {{
      mutate {{ rename => {{ "Channel" => "[winlog][channel]" "Provider" => "[event][provider]" }} }}
    }} else if [event_type] == "sysmon" {{
      mutate {{ add_field => {{ "[winlog][channel]" => "Microsoft-Windows-Sysmon/Operational"
                               "[event][provider]" => "Microsoft-Windows-Sysmon" }} }}
    }} else if [EventID] == 7045 {{
      mutate {{ add_field => {{ "[winlog][channel]" => "System" "[event][provider]" => "Service Control Manager" }} }}
    }} else if [EventID] == 1102 {{
      mutate {{ add_field => {{ "[winlog][channel]" => "Security" "[event][provider]" => "Microsoft-Windows-Eventlog" }} }}
    }} else {{
      mutate {{ add_field => {{ "[winlog][channel]" => "Security"
                               "[event][provider]" => "Microsoft-Windows-Security-Auditing" }} }}
    }}

    mutate {{
      add_field => {{ "[event][code]" => "%{{EventID}}" "[host][os][type]" => "windows" "[event][kind]" => "event" }}
    }}
    if [scenario] {{
      mutate {{
        rename => {{ "scenario" => "[labels][lab_scenario]" "event_id" => "[event][id]" "EventName" => "[event][action]" }}
        add_field => {{ "[event][dataset]" => "detection-lab.attack-simulator" }}
        remove_field => ["mitre_tactics", "event_type"]
      }}
    }} else {{
      mutate {{ add_field => {{ "[event][dataset]" => "detection-lab.log-generator" }} }}
    }}
    mutate {{ remove_field => ["EventID"] }}

    # Sigma field names to ECS field names.
    mutate {{
      rename => {{
{renames}
      }}
    }}

    # Every other field of the event goes under winlog.event_data as text, the way Winlogbeat stores it.
    ruby {{
      code => '
        keep = [{keep}]
        event.to_hash.keys.each do |name|
          next if keep.include?(name)
          value = event.remove(name)
          next if value.nil?
          value = value.join(", ") if value.is_a?(Array)
          event.set("[winlog][event_data][" + name + "]", value.to_s)
        end
      '
    }}
  }}

  if "linux_auth" in [tags] {{
    # detlab/authlog.py holds these three patterns next to the Python patterns that mirror them.
    grok {{
      match => {{ "message" => "{authlog.GROK_LINE}" }}
    }}
    date {{ match => ["[@metadata][stamp]", "MMM dd HH:mm:ss", "MMM  d HH:mm:ss"] timezone => "UTC" }}
    grok {{ match => {{ "message" => "{authlog.GROK_SOURCE}" }} tag_on_failure => [] }}
    grok {{ match => {{ "message" => "{authlog.GROK_USER}" }} tag_on_failure => [] }}
    mutate {{
      add_field => {{ "[event][dataset]" => "{authlog.DATASET}" "[host][os][type]" => "linux" "[event][kind]" => "event" }}
    }}
  }}

  if "firewall" in [tags] {{
    grok {{
      match => {{ "message" => "^%{{TIMESTAMP_ISO8601:[@metadata][stamp]}} %{{WORD:[event][action]}} %{{WORD:[network][transport]}} %{{IP:[source][ip]}}:%{{INT:[source][port]}} -> %{{IP:[destination][ip]}}:%{{INT:[destination][port]}}$" }}
    }}
    date {{ match => ["[@metadata][stamp]", "ISO8601"] timezone => "UTC" }}
    mutate {{
      lowercase => ["[event][action]", "[network][transport]"]
      add_field => {{ "[event][dataset]" => "detection-lab.firewall" "[event][category]" => "network" "[event][kind]" => "event" }}
    }}
  }}

  # One document per event, however often a file is read again.
  if ![event][id] {{
    fingerprint {{ source => ["message", "@timestamp", "winlog", "process", "destination"] concatenate_sources => true
                  method => "SHA256" target => "[event][id]" }}
  }}
  mutate {{ remove_field => ["@version"] }}
}}

output {{
  elasticsearch {{
    hosts => ["http://elasticsearch:9200"]
    user => "elastic"
    password => "${{ELASTIC_PASSWORD}}"
    index => "{LIVE_INDEX}"
    document_id => "%{{[event][id]}}"
    data_stream => false
    manage_template => false
    ilm_enabled => false
  }}
}}
'''


def index_template(body: dict) -> str:
    """The Elasticsearch index template for every detlab-* index, from the mapping siem.py builds."""
    template = {"index_patterns": ["detlab-*"], "priority": 200, "template": body,
                "_meta": {"description": "Detection Lab: keyword mappings for every field a rule can query"}}
    return json.dumps(template, indent=2) + "\n"
