"""The hunting exercises and attack chains in attack-simulator/scenarios/scenarios.yaml.

The file describes four attack chains to read through and four exercises to
solve on the simulator's events. Each exercise carries EQL queries that solve
it. This module turns the file into docs/EXERCISES.md and lets the stack job
prove that every query finds something.
"""

from typing import Any

import yaml

from detlab.rules import ROOT

SOURCE = ROOT / "attack-simulator" / "scenarios" / "scenarios.yaml"


def load() -> dict[str, Any]:
    return yaml.safe_load(SOURCE.read_text(encoding="utf-8"))


def queries() -> list[tuple[str, str]]:
    """(exercise name, EQL query) for every solution query."""
    return [(exercise["name"], query) for exercise in load()["exercises"] for query in exercise["solution_queries"]]


def _technique_link(technique: str) -> str:
    return f"[{technique}](https://attack.mitre.org/techniques/{technique.replace('.', '/')}/)"


def report() -> str:
    """docs/EXERCISES.md"""
    data = load()
    lines = [
        "# Exercises",
        "",
        "Generated by `python -m detlab build` from `attack-simulator/scenarios/scenarios.yaml`. "
        "Do not edit it by hand.",
        "",
        "## Hunting exercises",
        "",
        "Start the stack, load the data with `python -m detlab siem load` and work in Kibana Discover on the "
        "data view *Detection Lab: attack simulator scenarios*. Each exercise has hints and, further down, "
        "EQL queries that solve it. `python -m detlab siem exercises` runs those queries and prints how many "
        "events each one finds.",
        "",
    ]
    for number, exercise in enumerate(data["exercises"], start=1):
        lines += [f"### Exercise {number}: {exercise['name']}", "", f"**Objective:** {exercise['objective']}", "",
                  "Hints:", ""]
        lines += [f"- {hint}" for hint in exercise["hints"]]
        lines += ["", "<details><summary>Queries that solve it</summary>", "", "```eql"]
        lines += exercise["solution_queries"]
        lines += ["```", "", "</details>", ""]
    lines += [
        "## Attack chains to read through",
        "",
        "Four chains from first access to impact, with the technique of each step and what it leaves in the logs. "
        "They are reading material for planning detections. The simulator's six scenarios cover their building "
        "blocks, not these chains step by step.",
        "",
    ]
    for scenario in data["scenarios"]:
        title = scenario["name"].replace("_", " ").capitalize()
        lines += [f"### {title}", "", " ".join(scenario["description"].split()), "",
                  f"Difficulty: {scenario['difficulty']}. Estimated time: {scenario['estimated_duration']}.", "",
                  "| Step | Name | Technique | What to look for |", "| --- | --- | --- | --- |"]
        for step in scenario["attack_chain"]:
            indicators = "<br>".join(str(item) for item in step.get("indicators", []))
            lines.append(f"| {step['step']} | {step['name']} | {_technique_link(step['technique'])} | {indicators} |")
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"
