#!/usr/bin/env bash
# Create stack/.env with a fresh random value for every secret the stack needs.
#
#   stack/init.sh           create .env (refuses to overwrite one)
#   stack/init.sh --force   replace an existing .env
#
# Replacing .env after the stack has run once locks you out of the existing
# data volume, because Elasticsearch keeps the old password. Remove the volume
# first with: docker compose down -v
set -euo pipefail

cd "$(dirname "$0")"

if [ -e .env ] && [ "${1:-}" != "--force" ]; then
    echo "stack/.env already exists. Keep it or run with --force to replace it." >&2
    exit 1
fi

random_hex() {  # random_hex <bytes>
    head -c "$1" /dev/urandom | od -An -tx1 | tr -d ' \n'
}

umask 077
cat > .env <<ENV
# Generated by stack/init.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Do not commit this file.

# Password of the "elastic" user. Log in to Kibana with it.
ELASTIC_PASSWORD=$(random_hex 24)

# Password Kibana uses for its own account in Elasticsearch
KIBANA_PASSWORD=$(random_hex 24)

# Key Kibana uses to encrypt saved objects and sessions
KIBANA_ENCRYPTION_KEY=$(random_hex 32)

# The log generator and the attack simulator write stack/logs as this user
LAB_UID=$(id -u)
LAB_GID=$(id -g)
ENV
chmod 600 .env
echo "Wrote stack/.env with new secrets (file mode 600)."

# Logstash reads these folders as another user. They have to exist, owned by you and
# readable by everyone, before Docker mounts them.
(umask 022 && mkdir -p logs/windows logs/linux logs/network && chmod 755 logs logs/windows logs/linux logs/network)

if [ -r /proc/sys/vm/max_map_count ]; then
    current="$(cat /proc/sys/vm/max_map_count)"
    if [ "$current" -lt 262144 ]; then
        echo
        echo "vm.max_map_count is $current. Elasticsearch needs at least 262144:"
        echo "    sudo sysctl -w vm.max_map_count=262144"
    fi
fi
